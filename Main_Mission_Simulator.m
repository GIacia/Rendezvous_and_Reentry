function [r, v] = circular_polar_state_local(radius, u_rad, sys)
    r = radius * [cos(u_rad); 0; sin(u_rad)];
    z_over_r = sin(u_rad);
    v_mag = sqrt(sys.mu / radius * (1 - sys.J2 * (sys.Re / radius)^2 * (3*z_over_r^2 - 1)));
    v = v_mag * [-sin(u_rad); 0; cos(u_rad)];
end

