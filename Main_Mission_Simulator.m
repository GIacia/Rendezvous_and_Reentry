function sys = refresh_derived_sys_local(sys)
    r_insert = sys.Re + sys.h_insert;
    r_wait = sys.Re + sys.h_wait;
    a_transfer = 0.5 * (r_insert + r_wait);
    sys.phase = pi * (1 - (a_transfer / r_wait)^1.5);
end

